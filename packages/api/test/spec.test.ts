import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import createClient from "openapi-fetch";
import { afterEach, describe, expect, it, vi } from "vitest";
import { generateApi } from "../src/generate.js";
import { checkSpec } from "../src/testing.js";
import { openApiTypes, schemaType } from "../src/types.js";
import type { paths } from "./fixtures/generated.js";
import { DOC, testApi } from "./support/app.js";

const document = () => testApi().getOpenAPI31Document(DOC);

describe("checkSpec", () => {
  it("passes an API whose routes are all documented", () => {
    expect(
      checkSpec(testApi(), document(), { ignore: ["/openapi.json", "/boom"] }),
    ).toEqual([]);
  });

  it("reports undocumented routes, missing fields and duplicate ids", () => {
    const doc = structuredClone(document()) as unknown as {
      paths: Record<string, Record<string, Record<string, unknown>>>;
    };
    const get = doc.paths["/signups/{id}"]?.get as Record<string, unknown>;
    get.operationId = "listSignups";
    delete get.summary;
    get.tags = [];
    (doc.paths["/signups"] as Record<string, unknown>).put = {
      operationId: "putSignups",
      summary: "Not mounted",
      tags: ["Signups"],
      responses: { 200: { description: "x" } },
    };
    expect(checkSpec(testApi(), doc, { ignore: ["/openapi.json"] })).toEqual([
      "PUT /signups: response 200 has no schema",
      "GET /signups/{id}: operationId listSignups is also on GET /signups",
      "GET /signups/{id}: no summary",
      "GET /signups/{id}: no tags",
      "GET /boom: mounted but not documented",
      "PUT /signups: documented but not mounted",
    ]);
  });

  it("strips a base path from mounted routes", () => {
    const routes = [{ method: "GET", path: "/api/v1/things/:id" }];
    const doc = {
      paths: {
        "/things/{id}": {
          get: {
            operationId: "getThing",
            summary: "A thing",
            tags: ["T"],
            responses: { 204: { description: "ok" } },
          },
        },
      },
    };
    expect(checkSpec({ routes }, doc, { basePath: "/api/v1" })).toEqual([]);
  });
});

describe("openApiTypes", () => {
  it("matches the committed fixture, which tsc type-checks", () => {
    const fixture = readFileSync(
      new URL("./fixtures/generated.ts", import.meta.url),
      "utf8",
    );
    expect(fixture).toBe(
      `// Generated by workers-api from the OpenAPI document. Do not edit.\n\n${openApiTypes(document())}`,
    );
  });

  it("types an openapi-fetch client that calls the real routes", async () => {
    const app = testApi();
    const client = createClient<paths>({
      baseUrl: "http://api.test",
      fetch: (req: Request) => Promise.resolve(app.request(req)),
    });
    const page = await client.GET("/signups", { params: { query: {} } });
    const rows: { email: string; plan: "free" | "pro"; note: string | null }[] =
      page.data?.rows ?? [];
    expect(rows).toHaveLength(2);
    const one = await client.GET("/signups/{id}", {
      params: { path: { id: "s_1" } },
    });
    expect(one.data?.email).toBe("a@example.com");
    const missing = await client.GET("/signups/{id}", {
      params: { path: { id: "s_9" } },
    });
    expect(missing.error?.code).toBe("not_found");
    const created = await client.POST("/signups", {
      body: { email: "n@example.com", plan: "pro" },
    });
    expect(created.data?.plan).toBe("pro");
  });

  it("covers the schema forms Zod emits", () => {
    expect(schemaType({ type: ["string", "null"] })).toBe("string | null");
    expect(schemaType({ type: "string", nullable: true })).toBe(
      "string | null",
    );
    expect(schemaType({ const: "ok" })).toBe('"ok"');
    expect(schemaType({ enum: ["a", 1, null] })).toBe('"a" | 1 | null');
    expect(
      schemaType({ anyOf: [{ type: "string" }, { type: "number" }] }),
    ).toBe("string | number");
    expect(
      schemaType({
        allOf: [
          { $ref: "#/components/schemas/A" },
          {
            type: "object",
            properties: { b: { type: "integer" } },
            required: ["b"],
          },
        ],
      }),
    ).toBe('components["schemas"]["A"] & {\n  b: number;\n}');
    expect(
      schemaType({
        type: "array",
        items: { anyOf: [{ type: "string" }, { type: "null" }] },
      }),
    ).toBe("(string | null)[]");
    expect(
      schemaType({
        type: "array",
        prefixItems: [{ type: "string" }, { type: "number" }],
      }),
    ).toBe("[string, number]");
    expect(
      schemaType({ type: "object", additionalProperties: { type: "number" } }),
    ).toBe("{\n  [key: string]: number;\n}");
    expect(schemaType({ type: "object", additionalProperties: false })).toBe(
      "Record<string, never>",
    );
    expect(
      schemaType({
        type: "object",
        properties: { "a-b": { type: "boolean" } },
      }),
    ).toBe('{\n  "a-b"?: boolean;\n}');
    expect(schemaType({})).toBe("unknown");
  });
});

describe("generateApi", () => {
  let dir = "";
  afterEach(() => {
    if (dir) rmSync(dir, { recursive: true, force: true });
    process.exitCode = undefined;
  });

  it("writes the files, then --check passes until one goes stale", async () => {
    dir = mkdtempSync(join(tmpdir(), "workers-api-"));
    const outputs = [
      {
        document: document(),
        spec: "openapi/api.json",
        types: "src/generated/api.ts",
      },
    ];
    vi.spyOn(console, "log").mockImplementation(() => {});
    const error = vi.spyOn(console, "error").mockImplementation(() => {});

    const first = await generateApi(outputs, { root: dir, check: false });
    expect(first.written).toHaveLength(2);
    expect(
      JSON.parse(readFileSync(join(dir, "openapi/api.json"), "utf8")).info
        .title,
    ).toBe("Test API");

    expect(
      (await generateApi(outputs, { root: dir, check: true })).stale,
    ).toEqual([]);
    expect(process.exitCode).toBeFalsy();

    writeFileSync(join(dir, "src/generated/api.ts"), "// edited\n");
    const stale = await generateApi(outputs, {
      root: dir,
      check: true,
      command: "npm run gen",
    });
    expect(stale.stale).toHaveLength(1);
    expect(process.exitCode).toBe(1);
    expect(error.mock.calls[0]?.[0]).toContain("Run: npm run gen");
    expect(readFileSync(join(dir, "src/generated/api.ts"), "utf8")).toBe(
      "// edited\n",
    );
  });
});
