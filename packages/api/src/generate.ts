/**
 * Writes each API's OpenAPI document and its client types from the routes,
 * or with `--check` fails when the files on disk are stale. Node only.
 *
 *   // scripts/gen-api.ts
 *   import { generateApi } from "workers-api/generate";
 *   await generateApi([{ document: api().getOpenAPI31Document(DOC), spec: "openapi/api.json", types: "src/api/generated/api.ts" }]);
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative } from "node:path";
import { openApiTypes } from "./types.js";

export interface ApiOutput {
  /** The OpenAPI document, such as `app.getOpenAPI31Document(...)`. */
  document: object;
  /** Where to write the document as JSON, relative to `root`. */
  spec?: string;
  /** Where to write the types module, relative to `root`. */
  types?: string;
}

export interface GenerateOptions {
  /** The directory the output paths are relative to. Defaults to the current directory. */
  root?: string;
  /** Compare instead of write. Defaults to `--check` being in `process.argv`. */
  check?: boolean;
  /** The command to print when files are stale, such as `npm run gen`. */
  command?: string;
  /** Who generated the types, for the banner. */
  source?: string;
}

export interface GenerateResult {
  written: string[];
  stale: string[];
}

/** The file contents for each output, keyed by path relative to the root. */
export function apiFiles(
  outputs: readonly ApiOutput[],
  source = "workers-api",
): Map<string, string> {
  const files = new Map<string, string>();
  for (const { document, spec, types } of outputs) {
    if (spec) files.set(spec, `${JSON.stringify(document, null, 2)}\n`);
    if (types) {
      files.set(
        types,
        `// Generated by ${source} from the OpenAPI document. Do not edit.\n\n${openApiTypes(document)}`,
      );
    }
  }
  return files;
}

/**
 * Writes the files, or in check mode lists the stale ones. Prints what it did
 * and sets `process.exitCode = 1` when a check finds stale files.
 */
export async function generateApi(
  outputs: readonly ApiOutput[],
  options: GenerateOptions = {},
): Promise<GenerateResult> {
  const root = options.root ?? process.cwd();
  const check = options.check ?? process.argv.includes("--check");
  const result: GenerateResult = { written: [], stale: [] };
  for (const [path, content] of apiFiles(outputs, options.source)) {
    const file = isAbsolute(path) ? path : join(root, path);
    let current: string | null = null;
    try {
      current = readFileSync(file, "utf8");
    } catch {
      current = null;
    }
    if (current === content) continue;
    if (check) {
      result.stale.push(relative(process.cwd(), file));
      continue;
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
    result.written.push(relative(process.cwd(), file));
    console.log(`wrote ${relative(process.cwd(), file)}`);
  }
  if (result.stale.length > 0) {
    const fix = options.command ? `\nRun: ${options.command}` : "";
    console.error(
      `Generated API files are stale:\n  ${result.stale.join("\n  ")}${fix}`,
    );
    process.exitCode = 1;
  } else if (check) {
    console.log("generated API files are current");
  }
  return result;
}
